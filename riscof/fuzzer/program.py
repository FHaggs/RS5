"""Test program representation and rendering to a RISCOF-compatible assembly file.

Conventions for the generated body:
  * x31 is reserved: it holds the base of `fuzz_mem` (FUZZ_MEM_WORDS words, inside the
    signature region) so loads/stores done by the body are compared against Sail.
  * after the body, x1..x30 are dumped to `fuzz_regs`, also inside the signature.
  * the body is plain assembly: it is inserted after the C preprocessor has run, so no
    #define/#include and no // comments (use # for comments).

With `traps=True` the program also installs a trap handler (mtvec) and a trap log inside the
signature (`fuzz_traps`): x30 points to the log, x28/x29 are the handler's scratch registers,
so the body may only use x1..x27 for data (x28/x29 are fine as scratch in short sequences that
cannot trap in the middle). The handler:
  * exception: appends (mcause, mepc), sets mepc += 4 (no compressed instructions) and returns;
  * interrupt: appends (mcause, 0), clears mie.MTIE so the timer fires once per request, and
    returns; mepc is not logged because RS5 and Sail may take the interrupt at different
    instruction boundaries. The architectural state after the handler is the same either way;
  * always returns to M mode (sets mstatus.MPP = M), so an `ecall` ends a U-mode section.
The log holds MAX_TRAPS entries; later traps are counted but not stored.
"""
import re
from dataclasses import dataclass

FUZZ_MEM_WORDS = 64
MAX_TRAPS = 32

_TEMPLATE = """\
// Generated by the RS5 fuzzer: {name}
#include "model_test.h"
#include "arch_test.h"
RVTEST_ISA("{rvtest_isa}")

.section .text.init
.globl rvtest_entry_point
rvtest_entry_point:
RVMODEL_BOOT
RVTEST_CODE_BEGIN

#ifdef TEST_CASE_1

RVTEST_CASE(0,"{case_checks}def TEST_CASE_1=True;",fuzz)

{trap_init}
    la x31, fuzz_mem

// ---- fuzz body ----
{body}
// ---- end of fuzz body ----

    la x31, fuzz_regs
{dump}
{trap_handler}
#endif

RVTEST_CODE_END
RVMODEL_HALT

RVTEST_DATA_BEGIN
.align 4
rvtest_data:
.word 0xbabecafe
RVTEST_DATA_END

RVMODEL_DATA_BEGIN
rvtest_sig_begin:
sig_begin_canary:
CANARY;

fuzz_regs:
    .fill 32,4,0xdeadbeef
fuzz_mem:
{mem_init}
{trap_log}
sig_end_canary:
CANARY;
rvtest_sig_end:
RVMODEL_DATA_END
"""


_TRAP_INIT = """\
    la x30, fuzz_traps
    la x29, fuzz_trap_handler
    csrw mtvec, x29
    li x29, 0x8
    csrc mstatus, x29"""

_TRAP_HANDLER = """\
    j fuzz_trap_end
.align 4
fuzz_trap_handler:
    csrr  x29, mcause
    lw    x28, 0(x30)
    addi  x28, x28, 1
    sw    x28, 0(x30)
    sltiu x28, x28, {max_traps_plus_1}
    beqz  x28, fuzz_trap_full
    lw    x28, 0(x30)
    slli  x28, x28, 3
    add   x28, x28, x30
    sw    x29, 0(x28)
    bltz  x29, fuzz_trap_irq
    csrr  x29, mepc
    sw    x29, 4(x28)
    addi  x29, x29, 4
    csrw  mepc, x29
    j     fuzz_trap_ret
fuzz_trap_irq:
    li    x29, 0x80
    csrc  mie, x29
    j     fuzz_trap_ret
fuzz_trap_full:
    bltz  x29, fuzz_trap_irq
    csrr  x29, mepc
    addi  x29, x29, 4
    csrw  mepc, x29
fuzz_trap_ret:
    li    x29, 0x1800
    csrs  mstatus, x29
    mret
fuzz_trap_end:"""

_TRAP_LOG = """\
fuzz_traps:
    .fill {words},4,0"""


@dataclass
class Program:
    name: str
    body: str                 # assembly lines, must not write x31 (nor x28..x30 with traps)
    march: str = 'rv32i_zicsr'
    rvtest_isa: str = 'RV32I'
    mem_init: tuple = ()      # initial words of fuzz_mem (rest is 0xdeadbeef)
    spec: dict = None         # generator description (blocks/seeds), kept for the corpus and logs
    traps: bool = False       # install the trap handler and the trap log (see module docstring)

    def case_checks(self):
        """RVTEST_CASE checks so RISCOF only selects this test for a DUT ISA that supports it."""
        exts = re.findall(r'Z[a-z0-9]+|[A-Z]', self.rvtest_isa[4:])  # skip 'RV32'
        checks = ['check ISA:=regex(.*32.*);']
        checks += ['check ISA:=regex(.*{}.*);'.format(e) for e in exts]
        return ''.join(checks)

    def mem_asm(self):
        words = list(self.mem_init)[:FUZZ_MEM_WORDS]
        mem = ['    .word 0x{:08x}'.format(w & 0xffffffff) for w in words]
        if len(words) < FUZZ_MEM_WORDS:
            mem.append('    .fill {},4,0xdeadbeef'.format(FUZZ_MEM_WORDS - len(words)))
        return '\n'.join(mem)

    def render(self, body=None, mem_init=None):
        """Full .S file. body/mem_init override the program's own (used to build skeletons)."""
        dump = '\n'.join('    sw x{0}, {1}(x31)'.format(r, 4 * (r - 1)) for r in range(1, 31))
        return _TEMPLATE.format(name=self.name, rvtest_isa=self.rvtest_isa,
                                case_checks=self.case_checks(),
                                body=self.body if body is None else body,
                                dump=dump,
                                mem_init=self.mem_asm() if mem_init is None else mem_init,
                                trap_init=_TRAP_INIT if self.traps else '',
                                trap_handler=_TRAP_HANDLER.format(max_traps_plus_1=MAX_TRAPS + 1) if self.traps else '',
                                trap_log=_TRAP_LOG.format(words=2 * (MAX_TRAPS + 1)) if self.traps else '')

    def skeleton_key(self):
        """Programs with the same key share the same preprocessed skeleton."""
        return (self.march, self.rvtest_isa, self.traps)
